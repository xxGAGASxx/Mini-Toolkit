#!/usr/bin/env node
// Rebuilds js/icon-library.js from the PNG files in ./icons.
// Each sub-folder of ./icons becomes a group in the Icons panel.
// Usage:  node tools/build-icon-library.js
//
// Why embed? Browsers block reading a folder (and exporting images that use
// files) when index.html is opened straight from disk, so the icons are
// stored inside the script as data URLs.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const iconDir = path.join(root, 'icons');
const icons = [];

function addFile(file, folder) {
  if (!/\.png$/i.test(file)) return;
  const data = fs.readFileSync(file).toString('base64');
  icons.push({ name: path.basename(file).replace(/\.png$/i, ''), folder, src: 'data:image/png;base64,' + data });
}

for (const entry of fs.readdirSync(iconDir).sort()) {
  const full = path.join(iconDir, entry);
  if (fs.statSync(full).isDirectory()) {
    for (const file of fs.readdirSync(full).sort()) addFile(path.join(full, file), entry);
  } else {
    addFile(full, 'icons');
  }
}

const out = '// Generated by tools/build-icon-library.js. Edit the PNGs in /icons, then re-run the script.\n'
  + 'window.ICON_LIBRARY = [\n' + icons.map(i => JSON.stringify(i)).join(',\n') + '\n];\n';
fs.writeFileSync(path.join(root, 'js', 'icon-library.js'), out);
console.log(`Wrote ${icons.length} icons to js/icon-library.js`);
